#!/usr/bin/env node
// Writes CREDITS.md from the credits.json next to each asset folder in
// public/assets/ and the font licences in public/fonts/. Run it after any
// asset change: `node tools/credits.mjs`.

import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const ASSETS = join(ROOT, 'public', 'assets');

const AREAS = {
  characters: 'People',
  buildings: 'Buildings',
  street: 'Street furniture and vehicles',
  env: 'Ground, water, sky and props',
};

const licenceOf = (c) => c.licence ?? c.license ?? 'see source';

let md = `# Credits

Prompt Beach's own code, and every model, texture and animation generated by the
scripts in \`tools/assets/\`, are under the repository's MIT licence. The work of
others used here is listed below, with its licence and what was changed. Nothing
here is under a licence stricter than CC-BY; most is CC0 or MIT.

This file is generated by \`node tools/credits.mjs\` from the \`credits.json\`
files in \`public/assets/\`.
`;

for (const [dir, title] of Object.entries(AREAS)) {
  const file = join(ASSETS, dir, 'credits.json');
  if (!existsSync(file)) continue;
  const raw = JSON.parse(readFileSync(file, 'utf8'));
  const items = Array.isArray(raw) ? raw : (raw.credits ?? raw.items ?? []);
  // Group identical author + licence + source lines, listing the assets they cover.
  const groups = new Map();
  for (const c of items) {
    const key = JSON.stringify([c.author, licenceOf(c), c.url ?? c.source]);
    if (!groups.has(key)) groups.set(key, { c, assets: [] });
    groups.get(key).assets.push(c.asset);
  }
  md += `\n## ${title}\n\n`;
  for (const { c, assets } of groups.values()) {
    const link = c.url ? `[${c.source ?? c.url}](${c.url})` : (c.source ?? '');
    const list = assets.filter(Boolean);
    md += `- **${c.author}**, ${licenceOf(c)}${link ? `, ${link}` : ''}${list.length ? `: ${list.join(', ')}` : ''}.`;
    if (c.changes && !/^n\/?a\.?$/i.test(String(c.changes).trim())) md += ` ${String(c.changes).replace(/\.?$/, '.')}`;
    md += '\n';
  }
}

const fonts = join(ROOT, 'public', 'fonts');
if (existsSync(fonts)) {
  md += '\n## Fonts\n\n';
  for (const f of readdirSync(fonts).filter((n) => n.endsWith('.LICENSE')).sort()) {
    const name = f.replace(/\.LICENSE$/, '');
    const text = readFileSync(join(fonts, f), 'utf8');
    const licence = /SIL Open Font License/.test(text) ? 'SIL Open Font License 1.1' : /Apache License/.test(text) ? 'Apache License 2.0' : 'see licence file';
    const who = /Copyright[^\n]*/.exec(text)?.[0] ?? '';
    md += `- **${name[0].toUpperCase()}${name.slice(1)}**, ${licence}${who ? ` (${who.trim()})` : ''}. Self-hosted in \`public/fonts/\`.\n`;
  }
}

writeFileSync(join(ROOT, 'CREDITS.md'), md);
console.log('Wrote CREDITS.md');
